import { fileURLToPath, URL } from 'node:url'
import { defineConfig, type Plugin } from 'vite'
import react from '@vitejs/plugin-react'
import { VitePWA } from 'vite-plugin-pwa'

// Unique per production build. Baked into the JS bundle AND emitted to
// /version.json (excluded from SW precaching and served with no-store headers)
// so every open tab and installed home-screen PWA detects a new deploy within
// seconds and refreshes onto the current version.
const BUILD_ID = `${Date.now().toString(36)}`

function versionManifestPlugin(buildId: string): Plugin {
  return {
    name: 'larder-version-manifest',
    generateBundle() {
      this.emitFile({
        type: 'asset',
        fileName: 'version.json',
        source: `${JSON.stringify({ buildId })}\n`,
      })
    },
  }
}

export default defineConfig({
  define: {
    __APP_BUILD_ID__: JSON.stringify(BUILD_ID),
  },
  plugins: [
    react(),
    versionManifestPlugin(BUILD_ID),
    VitePWA({
      registerType: 'autoUpdate',
      // injectManifest, not generateSW: a generated worker cannot host the
      // `push` listener, and push is the point. src/sw.ts reproduces the
      // previous caching rules so offline behaviour is unchanged.
      strategies: 'injectManifest',
      srcDir: 'src',
      filename: 'sw.ts',
      // Registration + aggressive update polling is owned by src/lib/appUpdater.ts
      // (`updateViaCache: 'none'` + 60s/visibility checks), rather than the
      // default 134-byte registerSW.js stub which only checks on cold load.
      injectRegister: null,
      // The icons live in public/ and are generated by `npm run icons`.
      includeAssets: ['favicon.svg', 'favicon-32x32.png', 'apple-touch-icon.png'],
      manifest: {
        name: 'Larder',
        short_name: 'Groceries',
        description: 'A realtime household grocery list.',
        display: 'standalone',
        // `any` rather than `portrait`: locking orientation prevents installed
        // PWAs on tablets, foldables, ChromeOS and landscape phones from
        // rotating to fit the device's actual aspect ratio.
        orientation: 'any',
        theme_color: '#27583c',
        background_color: '#f2f8f4',
        start_url: '/',
        scope: '/',
        lang: 'en',
        categories: ['shopping', 'productivity', 'lifestyle'],
        icons: [
          { src: '/pwa-192x192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
          { src: '/pwa-512x512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
          {
            src: '/pwa-maskable-512x512.png',
            sizes: '512x512',
            type: 'image/png',
            purpose: 'maskable',
          },
        ],
      },
      injectManifest: {
        globPatterns: ['**/*.{js,css,html,ico,woff2}', 'pwa-*.png', 'apple-touch-icon.png', 'favicon*'],
        globIgnores: ['**/icons/**', 'version.json'],
      },
      workbox: {
        globPatterns: ['**/*.{js,css,html,ico,woff2}', 'pwa-*.png', 'apple-touch-icon.png', 'favicon*'],
        globIgnores: ['**/icons/**', 'version.json'],
        navigateFallback: '/index.html',
        cleanupOutdatedCaches: true,
        clientsClaim: true,
        skipWaiting: true,
        navigateFallbackDenylist: [/^\/functions\//, /^\/rest\//, /^\/auth\//, /^\/version\.json$/],
        runtimeCaching: [
          {
            urlPattern: ({ sameOrigin, url }) => sameOrigin && url.pathname.startsWith('/assets/'),
            handler: 'StaleWhileRevalidate',
            options: { cacheName: 'larder-assets' },
          },
          {
            urlPattern: ({ sameOrigin, url }) => sameOrigin && url.pathname.startsWith('/icons/'),
            handler: 'CacheFirst',
            options: {
              cacheName: 'larder-accent-icons',
              expiration: { maxEntries: 12, maxAgeSeconds: 60 * 60 * 24 * 90 },
            },
          },
        ],
      },
      devOptions: {
        enabled: false,
      },
    }),
  ],
  resolve: {
    alias: {
      '@': fileURLToPath(new URL('./src', import.meta.url)),
    },
  },
  server: {
    port: 5173,
    host: true,
  },
})
